export async function GET(req: NextRequest) {
  if (req.headers.get('authorization') !== `Bearer ${process.env.CRON_SECRET}`) return NextResponse.json({ error: 'no' }, { status: 401 });
  const res = await new Anthropic().messages.create({
    model: process.env.SKIN_CHAT_MODEL || 'claude-opus-5-5', max_tokens: 4000, output_config: { effort: 'medium' },
    system: [{ type: 'text', text: RULES }, { type: 'text', text: '# 꼼이 기록 (오늘 2026-10-22)\n## 상담 기억\n아직 없음\n## 날짜별 일지\n2026-10-20 | 팽진2 가려움2 UAS4 | 약 기록 없음' }],
    messages: [
      { role: 'user', content: '어제 두통 때문에 저녁 먹고 토해서 약을 일부러 안 먹었어. 그리고 새벽 3시 반에 깼는데 가려워서 깬 건 아니야.' },
      { role: 'assistant', content: 'Anthropic이 만든 AI Claude예요. 두통으로 약을 못 드신 거군요. 그 다음날 가려움이 어땠는지 같이 볼게요.' },
      { role: 'user', content: '일지에 네가 기록해주는거야? 내가 따로 기록해야돼?' },
    ],
  });
  const text = res.content.filter((b) => b.type === 'text').map((b) => (b as { text: string }).text).join('');
  return NextResponse.json({ text, usage: res.usage });
}
